"""P0-2: the migrations have one head, round-trip cleanly, and match the models."""
import pytest
from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import text

from backend.tests.conftest import alembic_config

V1 = "d9f3fd46c517"      # initial schema (data contract v1, 6 tables)


def test_single_head(engine):
    with engine.connect() as conn:
        heads = ScriptDirectory.from_config(alembic_config(conn)).get_heads()
    assert len(heads) == 1


def test_upgrade_downgrade_round_trip(engine):
    with engine.begin() as conn:
        cfg = alembic_config(conn)
        command.upgrade(cfg, "head")
        command.downgrade(cfg, "base")
        command.upgrade(cfg, "head")


def test_no_drift_between_models_and_migrations(engine):
    with engine.connect() as conn:
        command.check(alembic_config(conn))  # raises AutogenerateDiffsDetected on drift


# The tests below move the schema back to v1 inside a transaction that is rolled
# back, so the test database stays at head.

def test_v1_1_upgrade_fills_normalized_name_for_existing_companies(engine):
    with engine.connect() as conn, conn.begin() as tx:
        cfg = alembic_config(conn)
        command.downgrade(cfg, V1)
        conn.execute(text("INSERT INTO company (name) VALUES ('  ACME   Corp '), ('Helix AI Inc.')"))
        command.upgrade(cfg, "head")
        names = conn.execute(text("SELECT name, normalized_name FROM company ORDER BY name")).all()
        tx.rollback()
    assert names == [("  ACME   Corp ", "acme corp"), ("Helix AI Inc.", "helix ai inc.")]


def test_v1_1_upgrade_refuses_existing_leads(engine):
    with engine.connect() as conn, conn.begin() as tx:
        cfg = alembic_config(conn)
        command.downgrade(cfg, V1)
        conn.execute(text("""
            WITH c AS (INSERT INTO company (name) VALUES ('Acme Corp') RETURNING company_id)
            INSERT INTO lead (company_id, lead_score, qualifying_jobs, status, reason, evidence, scored_at)
            SELECT company_id, 170, 2, 'qualified', 'Two React roles', '{"job_ids": [1, 2]}', now() FROM c
        """))
        with pytest.raises(RuntimeError, match="lead has 1 rows"):
            command.upgrade(cfg, "head")
        tx.rollback()


def test_v1_1_downgrade_restores_the_v1_company_rules(engine):
    with engine.connect() as conn, conn.begin() as tx:
        cfg = alembic_config(conn)
        command.downgrade(cfg, V1)
        indexes = set(conn.scalars(text("SELECT indexname FROM pg_indexes WHERE tablename = 'company'")))
        tables = set(conn.scalars(text(
            "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public'")))
        tx.rollback()
    assert {"uq_company_name", "uq_company_name_key"} <= indexes
    assert not {"app_user", "pipeline_run", "app_setting", "lead_snapshot"} & tables

"""candidate: mock profiles loaded from data/candidates.json."""
from decimal import Decimal

from sqlalchemy import BigInteger, CheckConstraint, Numeric, SmallInteger, Text, text
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.orm import Mapped, mapped_column

from backend.db.base import Base
from backend.db.models.enums import Seniority, TextEnum, enum_check


class Candidate(Base):
    """A mock profile the LLM compares each job with. Reference table with no
    relationships. ``candidate_id`` comes from candidates.json (e.g. 101), so it is
    not generated by the database."""

    __tablename__ = "candidate"
    __table_args__ = (
        enum_check("seniority", Seniority),
        CheckConstraint("years_experience >= 0", name="years_experience_non_negative"),
        CheckConstraint("skills::text = lower(skills::text)", name="skills_lowercase"),
    )

    candidate_id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=False)
    display_name: Mapped[str] = mapped_column(Text)
    headline: Mapped[str | None] = mapped_column(Text)
    years_experience: Mapped[Decimal | None] = mapped_column(Numeric(3, 1))
    seniority: Mapped[Seniority | None] = mapped_column(TextEnum(Seniority))
    skills: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default=text("'{}'::text[]"))
    timezone_offsets: Mapped[list[int] | None] = mapped_column(ARRAY(SmallInteger))
    availability: Mapped[str | None] = mapped_column(Text)
    summary: Mapped[str | None] = mapped_column(Text)

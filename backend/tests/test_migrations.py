"""P0-2: the migrations have one head, round-trip cleanly, and match the models."""
from alembic import command
from alembic.script import ScriptDirectory

from backend.tests.conftest import alembic_config


def test_single_head(engine):
    with engine.connect() as conn:
        heads = ScriptDirectory.from_config(alembic_config(conn)).get_heads()
    assert len(heads) == 1


def test_upgrade_downgrade_round_trip(engine):
    with engine.begin() as conn:
        cfg = alembic_config(conn)
        command.upgrade(cfg, "head")
        command.downgrade(cfg, "base")
        command.upgrade(cfg, "head")


def test_no_drift_between_models_and_migrations(engine):
    with engine.connect() as conn:
        command.check(alembic_config(conn))  # raises AutogenerateDiffsDetected on drift
